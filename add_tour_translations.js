function updateFile(file, newKeys) {
  const fileFullPath = path.join(__dirname, file);
  const content = fs.readFileSync(fileFullPath, 'utf8');
  const data = JSON.parse(content);
  Object.assign(data, newKeys);
  fs.writeFileSync(fileFullPath, JSON.stringify(data, null, 2) + '\n');
  console.log(`Updated ${fileFullPath}`);
}

